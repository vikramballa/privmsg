//! Layer 2 — Metadata-private transport over the Nym mixnet.
//!
//! This crate carries opaque bytes (the MLS ciphertext from
//! `privmsg-crypto`) between two parties while hiding *who is talking to
//! whom* from a global passive adversary. It does that with three Nym
//! properties, none of which a plain VPN or TLS gives you:
//!
//!   1. **Sphinx packets** — fixed-size, layer-encrypted. To an observer,
//!      every packet looks identical; size and content reveal nothing.
//!   2. **Cover traffic** — the client emits packets at a constant
//!      Poisson-timed rate whether or not you have anything to say. Real
//!      messages are indistinguishable from decoys, so there is no burst
//!      or timing signature to correlate. This is the property Tor omits
//!      and the reason we are on a mixnet.
//!   3. **Hop separation** — the entry gateway learns your IP but not your
//!      destination; the exit learns the destination but not your IP. No
//!      single hop sees both ends. This is the correct version of the
//!      "fake IP in the metadata" idea: your real IP is never what the
//!      destination's metadata records.
//!
//! The address type below is the overlay (key-derived) identifier — a Nym
//! Sphinx recipient address, NOT an IP. It is what parties exchange to
//! reach each other.
//!
//! On top of Nym, every payload is padded to a multiple of [`PAD_BLOCK`]
//! before it is sent. A long message still splits into more Sphinx packets
//! than a short one, so without padding the packet count would leak message
//! length; with it, every ordinary chat message costs the same.
//!
//! [`Transport`] is the interface the node is written against. [`NymTransport`]
//! is the real mixnet; [`memory::MemoryNetwork`] is an in-process stand-in
//! for tests. This is the only crate that touches Nym.

use std::future::Future;
use std::path::Path;
use std::time::Duration;

use anyhow::{anyhow, Context, Result};
use futures::StreamExt;
use nym_sdk::mixnet::{
    IncludedSurbs, MixnetClient, MixnetClientBuilder, MixnetMessageSender, Recipient, StoragePaths,
};
use tokio::time::{sleep, Instant};

/// An overlay address: a Nym Sphinx recipient address (client id @ gateway).
/// NOT an IP. This is the "address generated by the application" — the thing
/// that appears in app-level metadata instead of a traceable network address.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MixAddress(pub String);

/// A message as it arrives from the mixnet: still MLS ciphertext. The
/// transport never sees plaintext.
#[derive(Clone, Debug)]
pub struct IncomingMessage {
    pub payload: Vec<u8>,
}

/// What the node needs from a transport. Implementations pad on send and
/// strip padding on receive, so callers only ever see the original bytes.
///
/// `recv` must be cancel-safe: the node races it against stdin in
/// `tokio::select!`, and a cancelled `recv` must not lose a message.
pub trait Transport {
    /// This client's own overlay address, to share with a contact.
    fn address(&self) -> MixAddress;

    /// Send already-encrypted bytes to `to`.
    fn send(&mut self, to: &MixAddress, payload: &[u8]) -> impl Future<Output = Result<()>> + Send;

    /// Await the next inbound message.
    fn recv(&mut self) -> impl Future<Output = Result<IncomingMessage>> + Send;
}

/// Payloads are padded up to a multiple of this many bytes.
pub const PAD_BLOCK: usize = 2048;

/// Largest payload accepted, before padding.
pub const MAX_PAYLOAD: usize = 64 * 1024;

const LEN_PREFIX: usize = 4;

/// Frame `payload` as `[u32 BE length][payload][zero fill]`, rounded up to a
/// multiple of [`PAD_BLOCK`].
pub fn pad(payload: &[u8]) -> Result<Vec<u8>> {
    if payload.len() > MAX_PAYLOAD {
        return Err(anyhow!(
            "payload of {} bytes exceeds the {MAX_PAYLOAD}-byte limit",
            payload.len()
        ));
    }
    let framed = LEN_PREFIX + payload.len();
    let padded = framed.div_ceil(PAD_BLOCK) * PAD_BLOCK;
    let mut out = Vec::with_capacity(padded);
    out.extend_from_slice(&(payload.len() as u32).to_be_bytes());
    out.extend_from_slice(payload);
    out.resize(padded, 0);
    Ok(out)
}

/// Inverse of [`pad`]. Rejects anything that is not a well-formed frame.
pub fn unpad(frame: &[u8]) -> Result<Vec<u8>> {
    if frame.is_empty() || !frame.len().is_multiple_of(PAD_BLOCK) {
        return Err(anyhow!("frame length {} is not a padded size", frame.len()));
    }
    let len = u32::from_be_bytes(frame[..LEN_PREFIX].try_into()?) as usize;
    if len > MAX_PAYLOAD || LEN_PREFIX + len > frame.len() {
        return Err(anyhow!("frame declares an impossible length {len}"));
    }
    Ok(frame[LEN_PREFIX..LEN_PREFIX + len].to_vec())
}

/// Thin wrapper over a Nym `MixnetClient`. One per participant.
pub struct NymTransport {
    client: MixnetClient,
}

impl NymTransport {
    /// Connect to the Nym mainnet, keeping the client's keys and gateway
    /// registration in `storage_dir` so the overlay address survives restarts.
    ///
    /// Background cover traffic and the Poisson send stream are on by default
    /// in the SDK. Do NOT disable them — they are the anonymity, not overhead
    /// to trim.
    pub async fn connect(storage_dir: &Path) -> Result<Self> {
        std::fs::create_dir_all(storage_dir)
            .with_context(|| format!("create {}", storage_dir.display()))?;
        let paths = StoragePaths::new_from_dir(storage_dir)?;
        let client = MixnetClientBuilder::new_with_default_storage(paths)
            .await?
            .build()?
            .connect_to_mixnet()
            .await
            .context("connect to the Nym mixnet")?;
        Ok(Self { client })
    }

    /// Wait until everything queued has been handed to the mixnet (or
    /// `timeout` passes). `send` only enqueues; exiting right after it would
    /// drop the message.
    pub async fn flush(&self, timeout: Duration) {
        let lanes = self.client.shared_lane_queue_lengths();
        let deadline = Instant::now() + timeout;
        // A just-sent message may still be on its way into the lane queue.
        sleep(Duration::from_millis(500)).await;
        while lanes.total() > 0 && Instant::now() < deadline {
            sleep(Duration::from_millis(200)).await;
        }
        // The queue counts messages, not packets already scheduled by the
        // Poisson sender; give the last ones a moment to leave.
        sleep(Duration::from_secs(3)).await;
    }

    /// Flush pending sends, then close the connection to the gateway.
    pub async fn disconnect(self) {
        self.flush(Duration::from_secs(30)).await;
        self.client.disconnect().await;
    }
}

impl Transport for NymTransport {
    fn address(&self) -> MixAddress {
        MixAddress(self.client.nym_address().to_string())
    }

    /// The payload is MLS ciphertext; the mixnet adds a second, routing layer
    /// of Sphinx encryption on top. No reply SURBs are attached: contacts
    /// already know each other's address, so SURBs would only cost bandwidth.
    async fn send(&mut self, to: &MixAddress, payload: &[u8]) -> Result<()> {
        let recipient: Recipient =
            to.0.parse()
                .map_err(|e| anyhow!("invalid mix address {:?}: {e}", to.0))?;
        self.client
            .send_message(recipient, pad(payload)?, IncludedSurbs::none())
            .await
            .context("hand message to the mixnet client")
    }

    /// Cover/decoy packets are handled by the SDK and never surface here.
    /// Malformed frames are dropped rather than ending the stream.
    async fn recv(&mut self) -> Result<IncomingMessage> {
        loop {
            let msg = self
                .client
                .next()
                .await
                .ok_or_else(|| anyhow!("mixnet client shut down"))?;
            if msg.message.is_empty() {
                continue;
            }
            match unpad(&msg.message) {
                Ok(payload) => return Ok(IncomingMessage { payload }),
                Err(e) => tracing::warn!("dropping malformed frame: {e}"),
            }
        }
    }
}

/// An in-process network for tests: endpoints exchange frames over channels,
/// with the same padding as the mixnet. Like a Nym gateway, it queues
/// messages for an address that is offline and delivers them on reconnect.
pub mod memory {
    use std::collections::HashMap;
    use std::sync::{Arc, Mutex};

    use anyhow::{anyhow, Result};
    use tokio::sync::mpsc::{unbounded_channel, UnboundedReceiver, UnboundedSender};

    use super::{pad, unpad, IncomingMessage, MixAddress, Transport};

    type Inbox = (UnboundedSender<Vec<u8>>, Option<UnboundedReceiver<Vec<u8>>>);

    #[derive(Clone, Default)]
    pub struct MemoryNetwork {
        inboxes: Arc<Mutex<HashMap<String, Inbox>>>,
    }

    impl MemoryNetwork {
        fn sender(&self, addr: &str) -> UnboundedSender<Vec<u8>> {
            let mut inboxes = self.inboxes.lock().unwrap();
            let (tx, _) = inboxes.entry(addr.to_string()).or_insert_with(|| {
                let (tx, rx) = unbounded_channel();
                (tx, Some(rx))
            });
            tx.clone()
        }

        /// Bring `addr` online. Fails if it is already online.
        pub fn connect(&self, addr: &str) -> Result<MemoryTransport> {
            self.sender(addr);
            let rx = self
                .inboxes
                .lock()
                .unwrap()
                .get_mut(addr)
                .and_then(|(_, rx)| rx.take())
                .ok_or_else(|| anyhow!("{addr} is already connected"))?;
            Ok(MemoryTransport {
                addr: addr.to_string(),
                net: self.clone(),
                rx: Some(rx),
            })
        }
    }

    pub struct MemoryTransport {
        addr: String,
        net: MemoryNetwork,
        rx: Option<UnboundedReceiver<Vec<u8>>>,
    }

    impl Drop for MemoryTransport {
        /// Going offline hands the inbox back so queued messages wait for us.
        fn drop(&mut self) {
            if let Some(rx) = self.rx.take() {
                if let Some((_, slot)) = self.net.inboxes.lock().unwrap().get_mut(&self.addr) {
                    *slot = Some(rx);
                }
            }
        }
    }

    impl Transport for MemoryTransport {
        fn address(&self) -> MixAddress {
            MixAddress(self.addr.clone())
        }

        async fn send(&mut self, to: &MixAddress, payload: &[u8]) -> Result<()> {
            let frame = pad(payload)?;
            self.net
                .sender(&to.0)
                .send(frame)
                .map_err(|_| anyhow!("network closed"))
        }

        async fn recv(&mut self) -> Result<IncomingMessage> {
            let frame = self
                .rx
                .as_mut()
                .expect("receiver present while connected")
                .recv()
                .await
                .ok_or_else(|| anyhow!("network closed"))?;
            Ok(IncomingMessage {
                payload: unpad(&frame)?,
            })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::memory::MemoryNetwork;
    use super::*;

    #[test]
    fn pad_roundtrip_and_uniform_size() -> Result<()> {
        for len in [0, 1, 100, PAD_BLOCK - LEN_PREFIX] {
            let payload = vec![7u8; len];
            let frame = pad(&payload)?;
            assert_eq!(frame.len(), PAD_BLOCK, "short messages share one size");
            assert_eq!(unpad(&frame)?, payload);
        }
        let big = vec![1u8; PAD_BLOCK];
        let frame = pad(&big)?;
        assert_eq!(frame.len(), 2 * PAD_BLOCK);
        assert_eq!(unpad(&frame)?, big);
        Ok(())
    }

    #[test]
    fn oversized_payload_is_refused() {
        assert!(pad(&vec![0u8; MAX_PAYLOAD + 1]).is_err());
        assert!(pad(&vec![0u8; MAX_PAYLOAD]).is_ok());
    }

    #[test]
    fn malformed_frames_are_rejected() {
        assert!(unpad(&[]).is_err());
        assert!(unpad(&[0u8; 100]).is_err(), "not a padded size");
        let mut lying = vec![0u8; PAD_BLOCK];
        lying[..4].copy_from_slice(&(PAD_BLOCK as u32).to_be_bytes());
        assert!(unpad(&lying).is_err(), "length larger than frame");
    }

    #[test]
    fn invalid_nym_address_is_rejected() {
        assert!("not-an-address".parse::<Recipient>().is_err());
    }

    #[tokio::test]
    async fn memory_network_delivers_and_queues_offline() -> Result<()> {
        let net = MemoryNetwork::default();
        let mut alice = net.connect("alice")?;
        alice.send(&MixAddress("bob".into()), b"queued").await?;

        let mut bob = net.connect("bob")?;
        assert!(net.connect("bob").is_err(), "one client per address");
        assert_eq!(bob.recv().await?.payload, b"queued");

        drop(bob);
        alice
            .send(&MixAddress("bob".into()), b"while offline")
            .await?;
        let mut bob = net.connect("bob")?;
        assert_eq!(bob.recv().await?.payload, b"while offline");
        Ok(())
    }
}
