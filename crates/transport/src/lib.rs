/// An overlay address: a Nym Sphinx recipient address (client id @ gateway).
/// NOT an IP. This is the "address generated by the application" — the thing
/// that appears in app-level metadata instead of a traceable network address.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MixAddress(pub String);

/// A message as it arrives from the mixnet: still MLS ciphertext. The
/// transport never sees plaintext.
#[derive(Clone, Debug)]
pub struct IncomingMessage {
    pub payload: Vec<u8>,
}

/// What the node needs from a transport. Implementations pad on send and
/// strip padding on receive, so callers only ever see the original bytes.
///
/// `recv` must be cancel-safe: the node races it against stdin in
/// `tokio::select!`, and a cancelled `recv` must not lose a message.
pub trait Transport {
    /// This client's own overlay address, to share with a contact.
    fn address(&self) -> MixAddress;

    /// Send already-encrypted bytes to `to`.
    fn send(&mut self, to: &MixAddress, payload: &[u8]) -> impl Future<Output = Result<()>> + Send;

    /// Await the next inbound message.
    fn recv(&mut self) -> impl Future<Output = Result<IncomingMessage>> + Send;

    /// Hand off anything still queued, then go offline.
    fn close(self) -> impl Future<Output = ()> + Send;
}

/// Opens endpoints by slot name. Each slot has its own keys, so its own
/// mix address; the same slot always reopens with the same address.
pub trait Network {
    type Endpoint: Transport + Send;

    /// A receive-only endpoint for `slot`.
    fn open(&self, slot: &str) -> impl Future<Output = Result<Self::Endpoint>> + Send;

    /// The endpoint everything is sent from. Its address is never shared.
    fn open_sender(&self) -> impl Future<Output = Result<Self::Endpoint>> + Send;

    /// Destroy a slot's keys for good. Its address can never receive again.
    fn forget(&self, slot: &str) -> Result<()>;
}

/// Several open slots, received from as one, plus the sender.
pub struct Mux<N: Network> {
    net: N,
    open: Vec<(String, N::Endpoint)>,
    /// `None` until something needs it, and while asleep.
    sender: Option<N::Endpoint>,
}

impl<N: Network> Mux<N> {
    pub fn new(net: N) -> Self {
        Self {
            net,
            open: Vec::new(),
            sender: None,
        }
    }

    pub fn is_open(&self, slot: &str) -> bool {
        self.open.iter().any(|(s, _)| s == slot)
    }

    pub fn address(&self, slot: &str) -> Option<MixAddress> {
        self.endpoint(slot).map(Transport::address)
    }

    /// Open every slot in `slots` that is not open yet, concurrently (each
    /// mixnet connection takes seconds), and the sender alongside so the
    /// first message doesn't wait for it. Returns the address of each slot.
    pub async fn open(&mut self, slots: &[String]) -> Result<Vec<MixAddress>> {
        let missing: Vec<&String> = slots.iter().filter(|s| !self.is_open(s)).collect();
        let wake = !slots.is_empty() && self.sender.is_none();
        let (opened, sender) = futures::join!(
            futures::future::join_all(missing.iter().map(|slot| self.net.open(slot))),
            async {
                if wake {
                    Some(self.net.open_sender().await)
                } else {
                    None
                }
            }
        );
        let mut first_error = None;
        for (slot, endpoint) in missing.into_iter().zip(opened) {
            match endpoint {
                Ok(endpoint) => self.open.push((slot.clone(), endpoint)),
                Err(e) => {
                    first_error.get_or_insert(e.context(format!("open address {slot}")));
                }
            }
        }
        match sender {
            Some(Ok(sender)) => self.sender = Some(sender),
            Some(Err(e)) => {
                first_error.get_or_insert(e.context("open the sender"));
            }
            None => {}
        }
        if let Some(e) = first_error {
            return Err(e);
        }
        Ok(slots
            .iter()
            .map(|s| self.address(s).expect("just opened"))
            .collect())
    }

    /// Send through the sender, waking it first if needed.
    pub async fn send(&mut self, to: &MixAddress, payload: &[u8]) -> Result<()> {
        self.wake().await?;
        let sender = self.sender.as_mut().expect("awake");
        sender.send(to, payload).await
    }

    /// Bring the sender online if it isn't.
    pub async fn wake(&mut self) -> Result<()> {
        if self.sender.is_none() {
            self.sender = Some(self.net.open_sender().await.context("open the sender")?);
        }
        Ok(())
    }

    /// Whether the sender is online (its cover stream running).
    pub fn is_awake(&self) -> bool {
        self.sender.is_some()
    }

    /// Flush and close the sender, stopping its cover stream; the next
    /// [`send`](Self::send) brings it back. Slots keep receiving.
    pub async fn sleep(&mut self) {
        if let Some(sender) = self.sender.take() {
            sender.close().await;
        }
    }

    /// The next message on any open slot, with the slot it arrived on.
    /// Never resolves while nothing is open. Cancel-safe, like
    /// [`Transport::recv`].
    pub async fn recv(&mut self) -> Result<(String, IncomingMessage)> {
        if self.open.is_empty() {
            return std::future::pending().await;
        }
        let receivers = self
            .open
            .iter_mut()
            .map(|(slot, endpoint)| Box::pin(async move { (slot.clone(), endpoint.recv().await) }));
        let ((slot, msg), _, _) = futures::future::select_all(receivers).await;
        Ok((
            slot.clone(),
            msg.with_context(|| format!("address {slot}"))?,
        ))
    }

    /// Close `slot` (if open) and destroy its keys.
    pub async fn forget(&mut self, slot: &str) -> Result<()> {
        if let Some(i) = self.open.iter().position(|(s, _)| s == slot) {
            self.open.remove(i).1.close().await;
        }
        self.net.forget(slot)
    }

    /// Flush and close every endpoint.
    pub async fn close(self) {
        let endpoints = self.open.into_iter().map(|(_, e)| e).chain(self.sender);
        futures::future::join_all(endpoints.map(Transport::close)).await;
    }

    /// Close every connection but keep the network (and its Tor), for when
    /// the connections may have died: the device changed networks, or was
    /// asleep. [`open`](Self::open) brings slots back on the same addresses.
    /// Connections that don't close within `timeout` are dropped.
    pub async fn reset(&mut self, timeout: Duration) {
        let endpoints: Vec<N::Endpoint> = self
            .open
            .drain(..)
            .map(|(_, e)| e)
            .chain(self.sender.take())
            .collect();
        let closing = futures::future::join_all(endpoints.into_iter().map(Transport::close));
        if tokio::time::timeout(timeout, closing).await.is_err() {
            tracing::warn!("some connections did not close in time; dropped them");
        }
    }

    fn endpoint(&self, slot: &str) -> Option<&N::Endpoint> {
        self.open.iter().find(|(s, _)| s == slot).map(|(_, e)| e)
    }
}

/// How much cover traffic is sent: the trade between data used and how
/// thick the stream your real packets hide in is.
///
/// The sender keeps both Nym streams running in every mode — a constant
/// Poisson-timed send stream (real packets take the next slot, cover fills
/// the rest) and loop cover — so real sends never show up as a burst; only
/// the rate changes. Slots never send, so they run loop cover alone, slower.
/// Measured on mainnet, the SDK default ([`DataMode::Maximum`]) costs about
/// 860 MB an hour.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum DataMode {
    /// About 10 MB an hour; messages wait a few seconds.
    #[default]
    Saver,
    /// About 35 MB an hour; messages wait a second or two.
    Balanced,
    /// The SDK default, tuned for a VPN's worth of traffic.
    Maximum,
}

impl DataMode {
    pub const ALL: [DataMode; 3] = [DataMode::Saver, DataMode::Balanced, DataMode::Maximum];

    pub fn name(self) -> &'static str {
        match self {
            DataMode::Saver => "saver",
            DataMode::Balanced => "balanced",
            DataMode::Maximum => "maximum",
        }
    }

    /// Rough data use of the sender per hour, for the user.
    pub fn mb_per_hour(self) -> u32 {
        match self {
            DataMode::Saver => 10,
            DataMode::Balanced => 35,
            DataMode::Maximum => 860,
        }
    }

    /// Rough data use of each open slot per hour, for the user.
    pub fn slot_mb_per_hour(self) -> f32 {
        match self {
            DataMode::Saver => 0.6,
            DataMode::Balanced => 2.3,
            DataMode::Maximum => 18.0,
        }
    }

    /// Mean gaps of the sender's send stream and of its loop cover, or
    /// `None` to keep the SDK defaults (20 ms and 200 ms).
    pub fn rates(self) -> Option<(Duration, Duration)> {
        match self {
            DataMode::Saver => Some((Duration::from_secs(2), Duration::from_secs(8))),
            DataMode::Balanced => Some((Duration::from_millis(500), Duration::from_secs(4))),
            DataMode::Maximum => None,
        }
    }

    /// Mean gap of a slot's loop cover. Every loop packet comes back through
    /// the slot's gateway looking like a delivered message.
    pub fn slot_loop(self) -> Duration {
        match self {
            DataMode::Saver => Duration::from_secs(30),
            DataMode::Balanced => Duration::from_secs(8),
            DataMode::Maximum => Duration::from_secs(1),
        }
    }

    /// Mean wait for a send-stream slot, which each outgoing packet pays.
    pub fn send_gap(self) -> Duration {
        self.rates()
            .map_or(Duration::from_millis(20), |(send, _)| send)
    }
}

impl std::str::FromStr for DataMode {
    type Err = anyhow::Error;

    fn from_str(s: &str) -> Result<Self> {
        DataMode::ALL
            .into_iter()
            .find(|m| m.name() == s)
            .ok_or_else(|| anyhow!("use saver, balanced or maximum"))
    }
}

/// Payloads are padded up to a multiple of this many bytes: exactly what
/// one Nym packet carries once Nym has added its own framing, so `k` blocks
/// travel as `k` packets (checked against Nym's code in `nym.rs`).
pub const PAD_BLOCK: usize = 1602;

/// Largest payload accepted, before padding.
pub const MAX_PAYLOAD: usize = 64 * 1024;

const LEN_PREFIX: usize = 4;

/// Frame `payload` as `[u32 BE length][payload][zero fill]`, rounded up to a
/// multiple of [`PAD_BLOCK`].
pub fn pad(payload: &[u8]) -> Result<Vec<u8>> {
    if payload.len() > MAX_PAYLOAD {
        return Err(anyhow!(
            "payload of {} bytes exceeds the {MAX_PAYLOAD}-byte limit",
            payload.len()
        ));
    }
    let framed = LEN_PREFIX + payload.len();
    let padded = framed.div_ceil(PAD_BLOCK) * PAD_BLOCK;
    let mut out = Vec::with_capacity(padded);
    out.extend_from_slice(&(payload.len() as u32).to_be_bytes());
    out.extend_from_slice(payload);
    out.resize(padded, 0);
    Ok(out)
}

/// Inverse of [`pad`]. Rejects anything that is not a well-formed frame.
pub fn unpad(frame: &[u8]) -> Result<Vec<u8>> {
    if frame.is_empty() || !frame.len().is_multiple_of(PAD_BLOCK) {
        return Err(anyhow!("frame length {} is not a padded size", frame.len()));
    }
    let len = u32::from_be_bytes(frame[..LEN_PREFIX].try_into()?) as usize;
    if len > MAX_PAYLOAD || LEN_PREFIX + len > frame.len() {
        return Err(anyhow!("frame declares an impossible length {len}"));
    }
    Ok(frame[LEN_PREFIX..LEN_PREFIX + len].to_vec())
}

/// An in-process network for tests: endpoints exchange frames over channels,
/// with the same padding as the mixnet. Like a Nym gateway, it queues
/// messages for an address that is offline and delivers them on reconnect.
pub mod memory {
    use std::collections::HashMap;
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::{Arc, Mutex};

    use anyhow::{anyhow, Result};
    use tokio::sync::mpsc::{unbounded_channel, UnboundedReceiver, UnboundedSender};

    use super::{pad, unpad, IncomingMessage, MixAddress, Network, Transport};

    type Inbox = (UnboundedSender<Vec<u8>>, Option<UnboundedReceiver<Vec<u8>>>);

    #[derive(Clone, Default)]
    pub struct MemoryNetwork {
        inboxes: Arc<Mutex<HashMap<String, Inbox>>>,
        senders: Arc<AtomicUsize>,
    }

    impl MemoryNetwork {
        fn sender(&self, addr: &str) -> UnboundedSender<Vec<u8>> {
            let mut inboxes = self.inboxes.lock().unwrap();
            let (tx, _) = inboxes.entry(addr.to_string()).or_insert_with(|| {
                let (tx, rx) = unbounded_channel();
                (tx, Some(rx))
            });
            tx.clone()
        }

        /// Bring `addr` online. Fails if it is already online.
        pub fn connect(&self, addr: &str) -> Result<MemoryTransport> {
            self.sender(addr);
            let rx = self
                .inboxes
                .lock()
                .unwrap()
                .get_mut(addr)
                .and_then(|(_, rx)| rx.take())
                .ok_or_else(|| anyhow!("{addr} is already connected"))?;
            Ok(MemoryTransport {
                addr: addr.to_string(),
                net: self.clone(),
                rx: Some(rx),
            })
        }
    }

    /// Slots map straight to addresses, so slot names must be unique across
    /// everyone sharing the network (privmsg's are random).
    impl Network for MemoryNetwork {
        type Endpoint = MemoryTransport;

        async fn open(&self, slot: &str) -> Result<MemoryTransport> {
            self.connect(slot)
        }

        async fn open_sender(&self) -> Result<MemoryTransport> {
            let n = self.senders.fetch_add(1, Ordering::Relaxed);
            self.connect(&format!("sender-{n}"))
        }

        fn forget(&self, slot: &str) -> Result<()> {
            self.inboxes.lock().unwrap().remove(slot);
            Ok(())
        }
    }

    pub struct MemoryTransport {
        addr: String,
        net: MemoryNetwork,
        rx: Option<UnboundedReceiver<Vec<u8>>>,
    }

    impl Drop for MemoryTransport {
        /// Going offline hands the inbox back so queued messages wait for us.
        fn drop(&mut self) {
            if let Some(rx) = self.rx.take() {
                if let Some((_, slot)) = self.net.inboxes.lock().unwrap().get_mut(&self.addr) {
                    *slot = Some(rx);
                }
            }
        }
    }

    impl Transport for MemoryTransport {
        fn address(&self) -> MixAddress {
            MixAddress(self.addr.clone())
        }

        async fn send(&mut self, to: &MixAddress, payload: &[u8]) -> Result<()> {
            let frame = pad(payload)?;
            self.net
                .sender(&to.0)
                .send(frame)
                .map_err(|_| anyhow!("network closed"))
        }

        async fn recv(&mut self) -> Result<IncomingMessage> {
            let frame = self
                .rx
                .as_mut()
                .expect("receiver present while connected")
                .recv()
                .await
                .ok_or_else(|| anyhow!("network closed"))?;
            Ok(IncomingMessage {
                payload: unpad(&frame)?,
            })
        }

        async fn close(self) {}
    }
}

#[cfg(test)]
mod tests {
    use super::memory::MemoryNetwork;
    use super::*;

    #[test]
    fn pad_roundtrip_and_uniform_size() -> Result<()> {
        for len in [0, 1, 100, PAD_BLOCK - LEN_PREFIX] {
            let payload = vec![7u8; len];
            let frame = pad(&payload)?;
            assert_eq!(frame.len(), PAD_BLOCK, "short messages share one size");
            assert_eq!(unpad(&frame)?, payload);
        }
        let big = vec![1u8; PAD_BLOCK - LEN_PREFIX + 1];
        let frame = pad(&big)?;
        assert_eq!(frame.len(), 2 * PAD_BLOCK);
        assert_eq!(unpad(&frame)?, big);
        Ok(())
    }

    #[test]
    fn oversized_payload_is_refused() {
        assert!(pad(&vec![0u8; MAX_PAYLOAD + 1]).is_err());
        assert!(pad(&vec![0u8; MAX_PAYLOAD]).is_ok());
    }

    #[test]
    fn malformed_frames_are_rejected() {
        assert!(unpad(&[]).is_err());
        assert!(unpad(&[0u8; 100]).is_err(), "not a padded size");
        let mut lying = vec![0u8; PAD_BLOCK];
        lying[..4].copy_from_slice(&(PAD_BLOCK as u32).to_be_bytes());
        assert!(unpad(&lying).is_err(), "length larger than frame");
    }

    #[tokio::test]
    async fn memory_network_delivers_and_queues_offline() -> Result<()> {
        let net = MemoryNetwork::default();
        let mut alice = net.connect("alice")?;
        alice.send(&MixAddress("bob".into()), b"queued").await?;

        let mut bob = net.connect("bob")?;
        assert!(net.connect("bob").is_err(), "one client per address");
        assert_eq!(bob.recv().await?.payload, b"queued");

        drop(bob);
        alice
            .send(&MixAddress("bob".into()), b"while offline")
            .await?;
        let mut bob = net.connect("bob")?;
        assert_eq!(bob.recv().await?.payload, b"while offline");
        Ok(())
    }

    #[tokio::test]
    async fn mux_tags_arrivals_with_their_slot() -> Result<()> {
        let net = MemoryNetwork::default();
        let mut mux = Mux::new(net.clone());
        let slots = vec!["one".to_string(), "two".to_string()];
        let addrs = mux.open(&slots).await?;
        assert_eq!(addrs[1], MixAddress("two".into()));
        assert_eq!(mux.open(&slots).await?.len(), 2, "reopening is a no-op");

        let mut peer = net.connect("peer")?;
        peer.send(&addrs[1], b"to two").await?;
        peer.send(&addrs[0], b"to one").await?;
        let mut got = [mux.recv().await?, mux.recv().await?];
        got.sort_by(|a, b| a.0.cmp(&b.0));
        assert_eq!(got[0].0, "one");
        assert_eq!(got[0].1.payload, b"to one");
        assert_eq!(got[1].0, "two");

        mux.forget("one").await?;
        assert!(!mux.is_open("one") && mux.is_open("two"));
        Ok(())
    }

    #[tokio::test]
    async fn everything_goes_out_through_the_sender() -> Result<()> {
        let net = MemoryNetwork::default();
        let mut mux = Mux::new(net.clone());
        let mut peer = net.connect("peer")?;
        let peer_addr = MixAddress("peer".into());

        // Sending needs no slot; the sender wakes on demand.
        assert!(!mux.is_awake());
        mux.send(&peer_addr, b"first").await?;
        assert!(mux.is_awake());
        assert_eq!(peer.recv().await?.payload, b"first");

        // Opening slots brings the sender up with them.
        mux.sleep().await;
        assert!(!mux.is_awake());
        let addrs = mux.open(&["one".to_string()]).await?;
        assert!(mux.is_awake());

        // Replies reach the slot, never the sender's own address.
        mux.send(&peer_addr, b"hi").await?;
        assert_eq!(peer.recv().await?.payload, b"hi");
        peer.send(&addrs[0], b"reply").await?;
        let (slot, msg) = mux.recv().await?;
        assert_eq!(
            (slot.as_str(), msg.payload.as_slice()),
            ("one", &b"reply"[..])
        );
        mux.close().await;
        Ok(())
    }
}
